#!/bin/bash
# Write apple/Config/Core-<platform>.xcconfig so the Xcode targets link the real
# emulator core from core/out/<platform>. Without this file the app builds against
# a mock core (handy for UI work and for CI's fast shell-only job).
set -euo pipefail

PLATFORM="${1:?usage: write-xcconfig.sh ios|macos}"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
CONF="${ROOT}/apple/Config/Core-${PLATFORM}.xcconfig"
OUTREL='$(SRCROOT)/../core/out/'"${PLATFORM}"

if [ "${PLATFORM}" = "ios" ]; then
    SDK='sdk=iphoneos*'
    FRAMEWORKS='-framework OpenGLES -framework QuartzCore -framework AudioToolbox -framework AVFoundation -framework CoreMotion -framework CoreHaptics -framework CoreVideo -framework CoreAudio'
else
    SDK='sdk=macosx*'
    FRAMEWORKS='-framework OpenGL -framework AppKit -framework QuartzCore -framework AudioToolbox -framework AudioUnit -framework CoreAudio -framework CoreServices -framework CoreVideo -framework IOKit -framework Carbon -F'"${OUTREL}"' -framework SDL2'
fi

cat > "${CONF}" <<EOF
// Generated by core/scripts/write-xcconfig.sh - do not edit, do not commit.
HALCYON_CORE_DEFINES[${SDK}] = HALCYON_REAL_CORE=1
HALCYON_CORE_HEADERS[${SDK}] = ${OUTREL}/include
HALCYON_CORE_LDFLAGS[${SDK}] = ${OUTREL}/libHalcyonCore.a -lc++ -lz -liconv ${FRAMEWORKS}
HALCYON_CORE_ASSETS[${SDK}] = ${OUTREL}/assets
EOF
echo "Wrote ${CONF}"
